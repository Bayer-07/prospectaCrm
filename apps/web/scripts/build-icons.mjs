// Builds the BZS One identity icons from src/icons/svg/*.svg.
// Outputs src/icons/index.tsx (React components), preview.html and style-spec.json.
// Run with `pnpm icons` after adding or editing an SVG.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/icons');
const spec = { name: 'bzs-one-icons', style: 'soft line', grid: 24, strokeWidth: 1.75, strokeLinecap: 'round', strokeLinejoin: 'round', cornerRadius: 3, padding: 2 };
const groups = {
  'Navegação': ['overview', 'pipeline', 'companies', 'contacts', 'tags', 'tasks', 'activities'],
  'Conversas': ['inbox', 'quick-replies', 'chatbot', 'campaigns', 'whatsapp', 'email', 'automations'],
  'Gestão e integrações': ['reports', 'connections', 'settings', 'integrations', 'api', 'mcp', 'webhooks', 'docs', 'ai'],
  'Atividades e métricas': ['call', 'meeting', 'note', 'people', 'revenue', 'target', 'overdue'],
};

const svgDir = path.join(root, 'svg');
const icons = Object.fromEntries(fs.readdirSync(svgDir).filter((file) => file.endsWith('.svg')).sort().map((file) => {
  const source = fs.readFileSync(path.join(svgDir, file), 'utf8');
  const inner = source.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  return [file.slice(0, -4), inner.split('\n').map((line) => line.trim()).join('')];
}));
const grouped = Object.values(groups).flat();
const ungrouped = Object.keys(icons).filter((name) => !grouped.includes(name));
const missing = grouped.filter((name) => !icons[name]);
if (ungrouped.length || missing.length) throw new Error(`Icon groups out of sync. Ungrouped: ${ungrouped.join(', ') || '-'}; missing: ${missing.join(', ') || '-'}`);

const pascal = (name) => name.replace(/(^|-)([a-z])/g, (_, __, letter) => letter.toUpperCase());
const jsx = (markup) => markup.replace(/\s([a-z]+)-([a-z])([a-z]*)=/g, (_, head, first, rest) => ` ${head}${first.toUpperCase()}${rest}=`);

const components = grouped.map((name) => `export const ${pascal(name)}Icon = createIcon('${name}', <>${jsx(icons[name])}</>);`).join('\n');
fs.writeFileSync(path.join(root, 'index.tsx'), `// Generated by scripts/build-icons.mjs from src/icons/svg. Do not edit by hand.
import type { ComponentType, ReactNode, SVGProps } from 'react';

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number | string; strokeWidth?: number | string };
/** Any icon component the app renders: BZS One identity icons or Lucide utilities. */
export type IconComponent = ComponentType<{ size?: number | string; strokeWidth?: number | string; className?: string }>;

function createIcon(name: string, children: ReactNode) {
  function Icon({ size = 24, strokeWidth = ${spec.strokeWidth}, className, ...props }: IconProps) {
    return <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="${spec.strokeLinecap}"
      strokeLinejoin="${spec.strokeLinejoin}"
      aria-hidden="true"
      className={\`bzs-icon bzs-icon-\${name}\${className ? \` \${className}\` : ''}\`}
      {...props}
    >{children}</svg>;
  }
  Icon.displayName = \`\${name}Icon\`;
  return Icon;
}

${components}
`);

const svg = (size, inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${spec.strokeWidth}" stroke-linecap="${spec.strokeLinecap}" stroke-linejoin="${spec.strokeLinejoin}">${inner}</svg>`;
const section = (title, size, className = '') => `<section class="${className}"><h2>${title}</h2>${Object.entries(groups).map(([group, names]) => `<h3>${group}</h3><div class="grid s${size}">${names.map((name) => `<div class="icon-card">${svg(size, icons[name])}<span class="label">${name}</span></div>`).join('')}</div>`).join('')}</section>`;
const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(root, 'preview.html'), `<!DOCTYPE html>
<html lang="pt-BR">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>BZS One — ícones</title>
<style>
  * { margin: 0; padding: 0; box-sizing: border-box; }
  body { max-width: 1200px; margin: 0 auto; padding: 2rem 16px; font-family: "Inter", system-ui, sans-serif; color: #1d1d1f; background: #f5f5f7; }
  h1 { font-size: 1.5rem; font-weight: 650; }
  .subtitle { margin: .25rem 0 1.5rem; color: #6e6e73; font-size: .9rem; }
  .spec { display: flex; flex-wrap: wrap; gap: .5rem 1.5rem; margin-bottom: 2rem; padding: 1rem 1.25rem; border: 1px solid #e3e3e8; border-radius: 12px; background: #fff; color: #444; font-size: .85rem; }
  .spec strong { color: #1d1d1f; }
  h2 { margin: 2rem 0 .75rem; padding-bottom: .5rem; border-bottom: 1px solid #e3e3e8; font-size: 1.1rem; font-weight: 650; }
  h3 { margin: 1.25rem 0 .6rem; color: #6e6e73; font-size: .8rem; font-weight: 600; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(104px, 1fr)); gap: .75rem; }
  .grid.s48 { grid-template-columns: repeat(auto-fill, minmax(132px, 1fr)); }
  .icon-card { display: flex; flex-direction: column; align-items: center; gap: .6rem; padding: 1rem .5rem; border: 1px solid #e3e3e8; border-radius: 12px; background: #fff; color: #0f6fa3; }
  .icon-card svg { flex-shrink: 0; }
  .s16 .icon-card, .s24 .icon-card { color: #1d1d1f; }
  .label { color: #6e6e73; font-size: .72rem; text-align: center; }
  .dark { margin-top: 2rem; padding: 1.5rem 2rem 2rem; border-radius: 16px; background: #000; }
  .dark h2 { color: #f5f5f7; border-bottom-color: #333; }
  .dark h3, .dark .label { color: #8e8e93; }
  .dark .icon-card { border-color: #2c2c2e; background: #1c1c1e; color: #5cbcea; }
</style>
</head>
<body>
<h1>BZS One — ícones de identidade</h1>
<p class="subtitle">${grouped.length} ícones · linha suave · gerado em ${today}</p>
<div class="spec"><span><strong>Grade:</strong> ${spec.grid}px</span><span><strong>Traço:</strong> ${spec.strokeWidth}px</span><span><strong>Pontas:</strong> ${spec.strokeLinecap}</span><span><strong>Junções:</strong> ${spec.strokeLinejoin}</span><span><strong>Raio:</strong> ${spec.cornerRadius}px</span><span><strong>Respiro:</strong> ${spec.padding}px</span></div>
${section('Tamanho de uso (16px)', 16)}
${section('Tamanho nativo (24px)', 24)}
${section('2× (48px), cor de destaque', 48)}
${section('Tema escuro (48px)', 48, 'dark')}
</body>
</html>
`);
fs.writeFileSync(path.join(root, 'style-spec.json'), `${JSON.stringify({ ...spec, iconCount: grouped.length, icons: grouped, generated: today }, null, 2)}\n`);
console.log(`Built ${grouped.length} icons.`);
